"""The tutor explains. It never decides whether a step succeeded.

Sources of an answer, always labelled in the response:
  curated   written and reviewed in tutor/knowledge/*.yaml (works offline, no API needed)
  derived   computed deterministically from your own experiment data (e.g. suggestions)
  source    text extracted from the actual code (docstrings), not paraphrased
  ai        generated by an optional configured provider; may be wrong, shown with a warning
"""

from __future__ import annotations

import ast
from functools import lru_cache
from pathlib import Path
from typing import Any

import yaml

from ..i18n import normalize, t
from ..sourcemap import safe_path, symbol_range
from .providers import configured_provider
from .redact import redact

KNOWLEDGE = Path(__file__).resolve().parent / "knowledge"
LEVELS = ("simple", "logic", "design", "tradeoffs")


@lru_cache(maxsize=1)
def concepts() -> dict[str, Any]:
    return yaml.safe_load((KNOWLEDGE / "concepts.yaml").read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def code_notes() -> dict[str, Any]:
    return yaml.safe_load((KNOWLEDGE / "code.yaml").read_text(encoding="utf-8"))


def _loc(d: dict[str, str] | None, lang: str) -> str | None:
    return None if not d else (d.get(lang) or d.get("en"))


def explain_concept(cid: str, level: str, lang: str) -> dict[str, Any]:
    lang, c = normalize(lang), concepts().get(cid)
    if not c:
        return {"source": "none", "text": t(lang, "tutor.unknown_concept", id=cid)}
    level = level if level in LEVELS else "simple"
    return {"source": "curated", "concept": cid, "level": level, "title": _loc(c["title"], lang),
            "text": _loc(c["levels"][level], lang), "analogy": _loc(c.get("analogy"), lang),
            "claim_type": c.get("claim_type", "established"), "references": c.get("references", []),
            "levels_available": [lv for lv in LEVELS if lv in c["levels"]]}


def _docstring(path: Path, symbol: str) -> str | None:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if getattr(node, "name", None) == symbol and isinstance(node, (ast.FunctionDef, ast.ClassDef,
                                                                      ast.AsyncFunctionDef)):
            return ast.get_docstring(node)
    return None


def explain_code(file: str, symbol: str | None, level: str, lang: str) -> dict[str, Any]:
    lang = normalize(lang)
    path = safe_path(file)
    key = f"{file}:{symbol}" if symbol else file
    note = code_notes().get(key)
    rng = symbol_range(path, symbol) if symbol else None
    if note and level in note:
        return {"source": "curated", "file": file, "symbol": symbol, "range": rng, "level": level,
                "text": _loc(note[level], lang), "claim_type": note.get("claim_type", "implementation")}
    doc = _docstring(path, symbol) if symbol else None
    return {"source": "source" if doc else "none", "file": file, "symbol": symbol, "range": rng, "level": level,
            "text": doc or t(lang, "tutor.no_curated_code"),
            "note": t(lang, "tutor.docstring_note") if doc else None}


def ask(question: str, context: dict[str, Any], lang: str) -> dict[str, Any]:
    """Free-form question. Uses an AI provider only if one is configured; otherwise curated search."""
    lang = normalize(lang)
    question = question.strip()[:2000]
    provider = configured_provider()
    if provider is None:
        hits = search_concepts(question, lang)
        return {"source": "curated", "provider": None, "text": t(lang, "tutor.no_provider"), "matches": hits}
    ctx_lines = []
    for k in ("mission", "step", "file", "symbol", "code", "command", "metric", "error"):
        if context.get(k):
            ctx_lines.append(f"{k}: {str(context[k])[:3000]}")
    system = (
        "You are the tutor inside Inference Lab, a local AI inference engineering workbench. "
        f"Answer in {'Traditional Chinese as used in Taiwan (zh-TW)' if lang == 'zh-TW' else 'English'}. "
        "Keep original technical terms (TTFT, KV cache, vLLM, flags, file paths, code) untranslated, "
        "then explain them. Start simple, add detail progressively, use one concrete analogy. "
        "Label each claim as one of: established finding, implementation detail, engineering heuristic, "
        "or assumption. If you are not sure, say so plainly. Never claim a step succeeded or failed: "
        "only the lab's deterministic checks decide that. Never invent citations or measurements."
    )
    user = redact("Context:\n" + "\n".join(ctx_lines) + f"\n\nQuestion: {question}")
    try:
        text = provider.complete(system, user)
    except Exception as e:  # noqa: BLE001
        return {"source": "curated", "provider": provider.name, "error": type(e).__name__,
                "text": t(lang, "tutor.provider_failed"), "matches": search_concepts(question, lang)}
    return {"source": "ai", "provider": provider.name, "text": text, "warning": t(lang, "tutor.ai_warning")}


def search_concepts(q: str, lang: str) -> list[dict[str, str]]:
    ql = q.lower()
    scored = []
    for cid, c in concepts().items():
        hay = " ".join([cid, *c.get("keywords", []), _loc(c["title"], "en") or "", _loc(c["title"], "zh-TW") or ""]).lower()
        score = sum(1 for w in set(ql.replace("?", " ").split()) if len(w) > 2 and w in hay)
        score += sum(2 for k in c.get("keywords", []) if k.lower() in ql)
        if score:
            scored.append((score, cid))
    return [{"id": cid, "title": _loc(concepts()[cid]["title"], lang)} for _, cid in sorted(scored, reverse=True)[:5]]


def suggest_optimizations(comparison: dict[str, Any], baseline: dict[str, Any], candidate: dict[str, Any],
                          lang: str) -> list[dict[str, Any]]:
    """Deterministic, evidence-first suggestions from a baseline/candidate comparison.

    Every suggestion carries: evidence, suspected cause, proposed change, expected impact,
    drawbacks, and how to validate it.
    """
    lang = normalize(lang)
    m = comparison["metrics"]
    diffs = comparison["comparability"]["differences"]
    pa, pb = baseline.get("params") or {}, candidate.get("params") or {}
    engine = (candidate.get("engine") or {}).get("name")
    out = []

    def pct(k: str) -> float | None:
        return (m.get(k) or {}).get("change_pct")

    ttft, thr = pct("ttft_p50_ms"), pct("output_throughput_tps")
    if diffs == ["workload.concurrency"] and ttft is not None and thr is not None:
        if (pb.get("concurrency", 0) > pa.get("concurrency", 0)) and ttft > 50 and thr < 25:
            key = "queueing_serial" if engine == "inference-lab-mini" else "queueing_saturated"
            out.append(_suggestion(key, lang, ttft=f"{ttft:.0f}", thr=f"{thr:.0f}",
                                   c1=pa.get("concurrency"), c2=pb.get("concurrency")))
        elif (pb.get("concurrency", 0) > pa.get("concurrency", 0)) and thr >= 25:
            out.append(_suggestion("batching_helps", lang, ttft=f"{ttft:.0f}", thr=f"{thr:.0f}",
                                   c1=pa.get("concurrency"), c2=pb.get("concurrency")))
    if diffs == ["workload.max_tokens"]:
        e2e = pct("e2e_p50_ms")
        if e2e is not None:
            out.append(_suggestion("decode_bound", lang, e2e=f"{e2e:.0f}", t1=pa.get("max_tokens"), t2=pb.get("max_tokens")))
    err = (m.get("error_rate") or {}).get("candidate")
    if err:
        out.append(_suggestion("errors_present", lang, rate=f"{err * 100:.0f}"))
    if len(diffs) > 1:
        out.append(_suggestion("confounded", lang, vars=", ".join(diffs)))
    return out


def _suggestion(key: str, lang: str, **kw: Any) -> dict[str, Any]:
    fields = ("evidence", "cause", "change", "impact", "drawbacks", "validation")
    return {"id": key, "source": "derived", "claim_type": "engineering_heuristic",
            **{f: t(lang, f"suggest.{key}.{f}", **kw) for f in fields}}
